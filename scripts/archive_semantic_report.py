"""Archive the semantic LLM navigation experiments into report/semantic-llm-20261111.

Reads the ignored local run roots and writes a small, shareable archive:
  README.md            English result index
  analysis.md          statistics generated by analyze_semantic_replicates.py
  episodes.csv         one row per episode (124), incl. time-to-find and LLM coverage
  prompts.md           the exact v1 / v2 system prompts
  provenance.json      run roots, model, git commit, preflight files
  find-time-by-group.png
"""
import argparse
import csv
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
sys.path.insert(0, str(ROOT / 'src'))
import analyze_semantic_replicates as analysis  # noqa: E402

POLICY_LABELS = {'nearest': 'Nearest', 'information_gain': 'Information Gain',
                 'llm_guided': 'LLM v1', 'llm_guided_v2': 'LLM v2'}
# Validated categorical slots 1-4 (light surface); values are direct-labelled for contrast relief.
COLORS = ['#2a78d6', '#eb6834', '#1baf7a', '#eda100']


def episode_rows(replicates):
    data = analysis.rows(replicates)
    positions = analysis.target_positions()
    out = []
    for row in data:
        found = analysis.time_to_find(row, positions)
        out.append(dict(
            start=row['start'], task_id=row['task_id'], placement=analysis.GROUPS[row['task_id']],
            target_region=row['target_region'], policy=row['policy'], termination=row['termination'],
            success=row['success'], simulated_time_s=round(row['simulated_time_s'], 2),
            capped_time_s=round(analysis.capped(row), 2), actual_distance_m=round(row['actual_distance_m'], 3),
            time_to_find_s=None if found is None else round(found, 2),
            first_selected_region=row['first_selected_region'], decisions=row['decisions'],
            llm_calls=row['llm_calls'], llm_fallbacks=row['llm_fallbacks'],
            llm_valid=row.get('llm_valid', True), wall_time_s=round(row['wall_time_s'] or 0, 1),
            run_root=str(Path(row['root']).relative_to(ROOT)).replace('\\', '/')))
    return out


def figure(rows, path):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from statistics import mean
    plt.rcParams['font.sans-serif'] = ['DejaVu Sans']
    plt.rcParams['axes.unicode_minus'] = False
    groups = [('consistent', 'Typical placements (16 groups) '), ('anomalous', 'Atypical placements (15 groups) ')]
    policies = list(POLICY_LABELS)
    fig, ax = plt.subplots(figsize=(8.4, 4.4), dpi=160)
    fig.patch.set_facecolor('#fcfcfb')
    ax.set_facecolor('#fcfcfb')
    width = .19
    for i, policy in enumerate(policies):
        values = []
        for key, _ in groups:
            sel = [r for r in rows if r['policy'] == policy and r['placement'] == key]
            values.append(mean(600. if r['time_to_find_s'] is None else r['time_to_find_s'] for r in sel))
        xs = [g + (i - 1.5) * (width + .015) for g in range(len(groups))]
        bars = ax.bar(xs, values, width, color=COLORS[i], label=POLICY_LABELS[policy],
                      edgecolor='#fcfcfb', linewidth=2)
        for bar, value in zip(bars, values):
            ax.text(bar.get_x() + bar.get_width() / 2, value + 4, f'{value:.0f}', ha='center',
                    va='bottom', fontsize=9, color='#3d3d3a')
    ax.set_xticks(range(len(groups)))
    ax.set_xticklabels([label for _, label in groups], fontsize=10, color='#3d3d3a')
    ax.set_ylabel('Mean time to first track the true target (Simulation s, lower is better) ', fontsize=9, color='#3d3d3a')
    ax.set_title('Search efficiency by placement semantics (4 starting poses, undiscovered targets receive 600 s) ', fontsize=11, color='#1f1f1e', loc='left')
    ax.set_ylim(0, ax.get_ylim()[1] * 1.1)
    ax.grid(axis='y', color='#e4e3dd', linewidth=.8)
    ax.set_axisbelow(True)
    for side in ('top', 'right', 'left'):
        ax.spines[side].set_visible(False)
    ax.spines['bottom'].set_color('#c3c2b7')
    ax.tick_params(axis='y', colors='#6b6a64', labelsize=9, length=0)
    ax.tick_params(axis='x', length=0)
    ax.legend(frameon=False, fontsize=9, ncol=4, loc='upper left', bbox_to_anchor=(0, -.1))
    fig.tight_layout()
    fig.savefig(path, facecolor=fig.get_facecolor())
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--replicates', type=Path, default=ROOT / 'runs/semantic-replicates-20261111')
    parser.add_argument('--output', type=Path, default=ROOT / 'report/semantic-llm-20261111')
    args = parser.parse_args()
    out = args.output
    out.mkdir(parents=True, exist_ok=True)

    rows = episode_rows(args.replicates)
    with (out / 'episodes.csv').open('w', newline='', encoding='utf-8-sig') as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    subprocess.run([sys.executable, str(ROOT / 'scripts/analyze_semantic_replicates.py'),
                    '--replicates', str(args.replicates), '--output', str(out / 'analysis.md')],
                   check=True, stdout=subprocess.DEVNULL)
    (out / 'README.md').write_text(
        '# Semantic-guidance results\n\n'
        f'This archive contains {len(rows)} episodes. Discovery and independently '
        'verified completion are separate metrics.\n\n'
        '- [Analysis](analysis.md)\n- [Episode data](episodes.csv)\n'
        '- [System prompts](prompts.md)\n- [Provenance](provenance.json)\n'
        '- [Discovery-time figure](find-time-by-group.png)\n', encoding='utf-8')

    from frontier_search.policies.provider import SYSTEM_PROMPT_V1, SYSTEM_PROMPT_V2
    (out / 'prompts.md').write_text(
        '# LLM System prompt\n\nThe two versions differ only in their system prompts; user messages (Candidate frontiers, Regions, observed objects, Execution feedback) are identical. \n\n'
        '## v1 (Original) \n\n```text\n' + SYSTEM_PROMPT_V1 + '\n```\n\n'
        '## v2 (structured, task independent) \n\n```text\n' + SYSTEM_PROMPT_V2 + '\n```\n', encoding='utf-8')

    figure(rows, out / 'find-time-by-group.png')

    commit = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=str(ROOT), stdout=subprocess.PIPE,
                            encoding='utf-8', check=False).stdout.strip()
    provenance = dict(
        generated_by='scripts/archive_semantic_report.py', git_commit=commit,
        episodes=len(rows), llm_provider='DeepSeek (api.deepseek.com)',
        llm_model='deepseek-flash (DeepSeek-V4.1-Flash), provider-default reasoning effort',
        llm_deadline_s={'S0 llm_guided': 30, 'all other LLM runs': 60},
        run_roots=sorted({row['run_root'] for row in rows}),
        configs=[f'configs/semantic-navigation-start-{k}.json' for k in ('S0', 'S1', 'S2', 'S3')],
        preflight={'S0': 'runs/semantic-navigation-smoke-20261110/preflight/preflight.json',
                   'S1': 'runs/preflight-start-S1/preflight.json',
                   'S2': 'runs/preflight-start-S2/preflight.json',
                   'S3': 'runs/preflight-start-S3/preflight-merged-7task.json'},
        excluded=['bottle-bathroom-ambiguous at S3 (target visible from start)',
                  'Gemini-era llm_guided rows in runs/semantic-navigation-smoke-20261110-r2 '
                  '(free-tier HTTP 429 fallbacks)'],
        note='Run roots are git-ignored local directories; this archive copies only derived results.')
    (out / 'provenance.json').write_text(json.dumps(provenance, indent=2, ensure_ascii=False), encoding='utf-8')
    print('archived', len(rows), 'episodes to', out)


if __name__ == '__main__':
    main()
