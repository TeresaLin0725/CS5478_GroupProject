"""Owner B: proposed adapter seam; concrete iGibson integration is pending.

The adapter exposes no scene maps, semantic room labels or object instances.
Provide evaluator-only retained records through a separate private capability.
Runner owns stepping; Navigator.poll must never advance simulation.
"""
from typing import Protocol, Tuple


from ..contracts import GridCell, Pose, RGBDObservation


class SimulatorAdapter(Protocol):
    def reset(self, episode_id: str, scene_id: str, start_pose: Pose, seed: int) -> None: ...
    def verify_spawn_clearance(self) -> Tuple[GridCell, ...]: ...
    def capture(self) -> RGBDObservation: ...
    def current_pose(self) -> Pose: ...
    def step(self) -> None: ...
    def stop(self) -> None: ...
    def pause(self) -> None: ...
    def resume(self) -> None: ...
    def close(self) -> None: ...


class ControlledSimulatorAdapter(SimulatorAdapter, Protocol):
    """W2 adapter additions required by B's controller and C's budgets."""
    def sim_time_s(self) -> float: ...
    def set_velocity(self, linear_mps: float, angular_radps: float) -> None: ...
